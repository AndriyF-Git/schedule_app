/**
 * Скрипт для керування інтерактивністю застосунку розкладу.
 */

document.addEventListener('DOMContentLoaded', function() {
    // === 1. Підтвердження видалення записів розкладу ===
    
    // Знаходимо всі форми, призначені для видалення (з класом .delete-form)
    const deleteForms = document.querySelectorAll('.delete-form');

    deleteForms.forEach(form => {
        form.addEventListener('submit', function(event) {
            // Запобігаємо стандартній відправці форми
            event.preventDefault(); 
            
            // Запитуємо підтвердження у користувача
            const isConfirmed = confirm('Ви впевнені, що бажаєте видалити цей запис розкладу? Цю дію не можна скасувати.');

            if (isConfirmed) {
                // Якщо користувач підтвердив, відправляємо форму
                this.submit();
            }
            // Якщо не підтвердив, форма залишається на місці і нічого не відбувається
        });
    });

    // === 2. Додаткова функціональність (якщо знадобиться) ===
    
    // Тут можуть бути додані функції для:
    // - Клієнтської валідації інших форм
    // - Динамічної зміни контенту без перезавантаження сторінки (AJAX)
    // - Фільтрації таблиць на стороні клієнта (пошук)
    
});